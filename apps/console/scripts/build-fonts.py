#!/usr/bin/env python3
"""
Builds the console's self-hosted fonts (Rosh 27 type: Geist, Geist Mono,
Newsreader, Material Symbols Rounded) from their official npm packages.

  mkdir /tmp/fonts && cd /tmp/fonts
  npm i --no-save geist@1.8.1 @fontsource-variable/newsreader@5 material-symbols@0.48.1
  pip install fonttools brotli
  python3 <repo>/apps/console/scripts/build-fonts.py /tmp/fonts/node_modules

Geist and Geist Mono: variable weight, cut to Latin, features kept (tabular figures).
Newsreader Italic: variable weight, Latin.
Material Symbols Rounded: pinned to GRAD 0 and opsz 24, keeps FILL and wght, cut to
the icons in ICONS. Icons are drawn by code point, so the ligatures are dropped;
src/ui/icon-points.ts maps names to code points.
"""
import io, json, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

ICONS = """
space_dashboard mic mic_off door_front menu close check_circle check lock lock_open warning error info
verified verified_user shield_lock schedule videocam doorbell dialpad tv smartphone sensors restart_alt
bedtime medical_services emergency signpost play_arrow send photo_camera add_photo_alternate chevron_right
expand_more history help qr_code_2 light_mode dark_mode contrast smart_toy graphic_eq notifications person
keyboard terminal auto_awesome visibility link open_in_new stop bolt policy fact_check travel_explore
data_object front_hand sms home key password do_not_disturb_on block record_voice_over campaign timer sync
cancel arrow_forward edit_note nightlight touch_app frame_inspect manage_search psychology description image
undo replay science experiment cottage hourglass_top network_node radio_button_checked ring_volume vpn_key
security sticky_note_2 chat_bubble arrow_upward arrow_back more_horiz package_2 inventory_2
""".split()

LATIN = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x131, 0x152, 0x153, 0x2C6, 0x2DA, 0x2DC, 0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D,
    0x201E, 0x2022, 0x2026, 0x2032, 0x2033, 0x2039, 0x203A, 0x2044, 0x20AC, 0x2122, 0x2190, 0x2192,
    0x2212, 0x2264, 0x2265,
]

mods = Path(sys.argv[1])
out = Path(__file__).resolve().parent.parent / "src" / "fonts"
out.mkdir(parents=True, exist_ok=True)


def load(path):
    if not path.exists():
        sys.exit(f"missing {path}")
    return TTFont(str(path))


def reload(font):
    # Round-trip so the subsetter sees complete tables after instancing.
    buf = io.BytesIO()
    font.flavor = None
    font.save(buf)
    buf.seek(0)
    return TTFont(buf)


def save(font, name, unicodes, features=("*",)):
    font = reload(font)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = list(features)
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    font.flavor = "woff2"
    path = out / name
    font.save(str(path))
    print(f"{name}: {path.stat().st_size // 1024} KB")


fonts = mods / "geist" / "dist" / "fonts"
save(load(fonts / "geist-sans" / "Geist-Variable.woff2"), "geist.woff2", LATIN)
save(load(fonts / "geist-mono" / "GeistMono-Variable.woff2"), "geist-mono.woff2", LATIN)
save(load(mods / "@fontsource-variable" / "newsreader" / "files" / "newsreader-latin-wght-italic.woff2"), "newsreader-italic.woff2", LATIN)

icons = load(mods / "material-symbols" / "material-symbols-rounded.woff2")
cmap = icons.getBestCmap()
rev = {}
for cp, g in cmap.items():
    rev.setdefault(g, cp)
g2c = {g: chr(cp) for cp, g in cmap.items() if cp < 0x80}
names = {}
for lookup in icons["GSUB"].table.LookupList.Lookup:
    for st in lookup.SubTable:
        st = st.ExtSubTable if lookup.LookupType == 7 else st
        for first, ligs in getattr(st, "ligatures", {}).items():
            for lig in ligs:
                try:
                    names["".join(g2c[c] for c in [first, *lig.Component])] = lig.LigGlyph
                except KeyError:
                    pass
points = {}
for n in ICONS:
    if n not in names or names[n] not in rev:
        sys.exit(f"no icon named {n}")
    points[n] = rev[names[n]]
icons = instancer.instantiateVariableFont(icons, {"GRAD": 0, "opsz": 24})
save(icons, "material-symbols-rounded.woff2", sorted(points.values()), features=())

ts = out.parent / "ui" / "icon-points.ts"
body = ",\n".join(f"  {json.dumps(k)}: 0x{v:x}" for k, v in sorted(points.items()))
ts.write_text(
    "// Generated by scripts/build-fonts.py: Material Symbols Rounded code points.\n"
    f"export const ICON_POINTS = {{\n{body},\n}} as const;\n"
    "export type IconName = keyof typeof ICON_POINTS;\n"
)
print(f"{ts.name}: {len(points)} icons")
